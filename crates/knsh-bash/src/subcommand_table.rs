//! The tools with subcommands, as data (KNSH-037; FR-POL-15, FR-LC-06, FR-NET-03).
//!
//! Each [`SubcommandTool`] entry lists a tool's global options (only those accepted *before* the subcommand) and its
//! subcommands with their network-intent classes. Adding a tool, an option or a subcommand is an edit to this table,
//! never to the reading code in `subcommands`; `default_table_is_well_formed` checks every entry.
//!
//! Every entry was written from the tool's own manual or `--help` (`git(1)`, `npm help config`, `pnpm --help`,
//! `yarn --help`, `cargo --help`, `docker --help`, `kubectl options`, `gh --help`, `terraform -help`, `pip --help`,
//! `go help`). Lists are deliberately incomplete: a global option missing here makes the command fall back to its raw
//! argv with no classes, which is the safe direction. A subcommand missing here does the same, so third-party
//! subcommands (`cargo nextest`), aliases defined by configuration (`git co`) and package scripts run as subcommands
//! (`yarn build`) are never guessed.
//!
//! # Choosing classes
//!
//! A subcommand's classes are everything it may do on the network as the tool's intent, and a host rule must allow
//! all of them (KNSH-060). So publishing commands carry `network:publish`, commands that only download or read remote
//! state carry `network:fetch`, local commands carry `network:none`, and a group whose members differ (`gh pr`,
//! `docker image`) carries the union. Commands that run project code (`npm run`, `cargo run`) are classed by what the
//! tool itself does: the code they run is limited by the sandbox and the proxy, like any other.

use crate::subcommands::{NetworkClass, Subcommand, SubcommandTool};

const NONE: &[NetworkClass] = &[NetworkClass::None];
const FETCH: &[NetworkClass] = &[NetworkClass::Fetch];
const PUBLISH: &[NetworkClass] = &[NetworkClass::Publish];
const FETCH_PUBLISH: &[NetworkClass] = &[NetworkClass::Fetch, NetworkClass::Publish];

/// A subcommand without aliases.
const fn sub(name: &'static str, classes: &'static [NetworkClass]) -> Subcommand {
    Subcommand {
        name,
        aliases: &[],
        classes,
    }
}

/// A subcommand with aliases.
const fn alias(name: &'static str, aliases: &'static [&'static str], classes: &'static [NetworkClass]) -> Subcommand {
    Subcommand { name, aliases, classes }
}

